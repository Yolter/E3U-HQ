export const DICTIONARIES: Record<Lang, Dict> = { ru, en: en as Dict, es, tr };

export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string>): string {
  let out = DICTIONARIES[lang]?.[key] ?? (en as Dict)[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, v);
  }
  return out;
}

/** Backend error details are translation keys ("error.email_taken"). */
export function translateError(lang: Lang, detail: unknown): string {
  if (typeof detail === "string") {
    const base = detail.split(":")[0];
    const dict = DICTIONARIES[lang] as Record<string, string>;
    if (dict[base]) return dict[base];
  }
  return translate(lang, "error.generic");
}

export interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TranslationKey, vars?: Record<string, string>) => string;
  tError: (detail: unknown) => string;
}

export const I18nContext = createContext<I18nValue>({
  lang: "ru",
  setLang: () => {},
  t: (key) => translate("ru", key),
  tError: (detail) => translateError("ru", detail),
});

export const useI18n = () => useContext(I18nContext);
